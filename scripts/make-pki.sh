#!/usr/bin/env bash
# make-pki.sh — create the C2paSeal TEST PKI in testdata/pki/.
#
#   *** TEST ONLY. These keys are committed to the repo and are public. ***
#   *** Never use them to sign anything outside this test suite.        ***
#
# Produces an ES256 (P-256) chain shaped like a C2PA claim-signing chain:
#   root CA -> intermediate CA -> leaf
# plus an expired leaf (same intermediate) for the expired-cert fixture.
#
# Leaf profile (C2PA spec 2.4, "X.509 certificates"):
#   - basicConstraints CA:FALSE, keyUsage digitalSignature (critical)
#   - extendedKeyUsage present, without anyExtendedKeyUsage, containing
#     id-kp-emailProtection and id-kp-documentSigning
#   - SKI/AKI present, not self-signed
#
# Requires OpenSSL 3.4+ (for x509 -not_before / -not_after).
# Usage: scripts/make-pki.sh   (run from the repo root; overwrites testdata/pki)
set -euo pipefail

# Git Bash on Windows rewrites arguments starting with "/" (e.g. -subj).
export MSYS_NO_PATHCONV=1

OUT=testdata/pki
rm -rf "$OUT"
mkdir -p "$OUT"
cd "$OUT"

ext=extensions.cnf
cat > "$ext" <<'EOF'
[root]
basicConstraints = critical, CA:TRUE
keyUsage = critical, keyCertSign, cRLSign
subjectKeyIdentifier = hash

[intermediate]
basicConstraints = critical, CA:TRUE, pathlen:0
keyUsage = critical, keyCertSign, cRLSign
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid:always

[leaf]
basicConstraints = critical, CA:FALSE
keyUsage = critical, digitalSignature
extendedKeyUsage = emailProtection, 1.3.6.1.5.5.7.3.36
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid:always
EOF

key() { openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$1" 2>/dev/null; }

subj_base="/O=C2paSeal TEST ONLY/OU=Not for production"

# Root CA (self-signed), 20 years.
key root.key
openssl req -new -sha256 -key root.key -subj "$subj_base/CN=C2paSeal Test Root CA" -out root.csr
openssl x509 -req -sha256 -in root.csr -signkey root.key -days 7300 \
  -extfile "$ext" -extensions root -set_serial 0x1001 -out root.pem
rm root.csr

# Intermediate CA, 10 years.
key intermediate.key
openssl req -new -sha256 -key intermediate.key \
  -subj "$subj_base/CN=C2paSeal Test Intermediate CA" -out intermediate.csr
openssl x509 -req -sha256 -in intermediate.csr -CA root.pem -CAkey root.key \
  -set_serial 0x2001 -days 3650 -extfile "$ext" -extensions intermediate \
  -out intermediate.pem
rm intermediate.csr

# Leaf signer, 5 years.
key leaf.key
openssl req -new -sha256 -key leaf.key \
  -subj "$subj_base/CN=C2paSeal Test Signer" -out leaf.csr
openssl x509 -req -sha256 -in leaf.csr -CA intermediate.pem -CAkey intermediate.key \
  -set_serial 0x3001 -days 1825 -extfile "$ext" -extensions leaf -out leaf.pem
rm leaf.csr

# Expired leaf: valid 2020-01-01 .. 2021-01-01.
key expired.key
openssl req -new -sha256 -key expired.key \
  -subj "$subj_base/CN=C2paSeal Test Signer (expired)" -out expired.csr
openssl x509 -req -sha256 -in expired.csr -CA intermediate.pem -CAkey intermediate.key \
  -set_serial 0x3002 -not_before 20200101000000Z -not_after 20210101000000Z \
  -extfile "$ext" -extensions leaf -out expired.pem
rm expired.csr

# Chains for signing: leaf first, then intermediate (root is the trust anchor).
cat leaf.pem intermediate.pem > leaf-chain.pem
cat expired.pem intermediate.pem > expired-chain.pem
cp root.pem trust-anchors.pem

# Convert keys to PKCS#8 PEM (what c2patool expects).
for k in root intermediate leaf expired; do
  openssl pkcs8 -topk8 -nocrypt -in "$k.key" -out "$k.key.tmp" && mv "$k.key.tmp" "$k.key"
done
rm "$ext"

cat > README.md <<'EOF'
# TEST ONLY PKI

Generated by `scripts/make-pki.sh`. These private keys are public. They exist
only to sign test fixtures and must never be trusted for anything else.

| File | What |
|---|---|
| `root.pem` / `root.key` | Test root CA (also `trust-anchors.pem`) |
| `intermediate.pem` / `.key` | Test intermediate CA |
| `leaf.pem` / `leaf.key` | ES256 claim signer, valid 5 years from generation |
| `expired.pem` / `.key` | ES256 claim signer, valid only 2020-01-01 to 2021-01-01 |
| `leaf-chain.pem`, `expired-chain.pem` | Signer + intermediate, as passed to `c2patool` |
EOF

openssl verify -CAfile root.pem -untrusted intermediate.pem leaf.pem
echo "TEST ONLY PKI written to $OUT"
