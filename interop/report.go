type result struct {
	Tool    string
	Mode    mode
	Outcome outcome
}

type row struct {
	Item    item
	Facts   []string
	Results []result
}

type report struct {
	Generated time.Time
	Root      string
	Tools     []toolInfo
	Rows      []row
}

// disagreement is one file and mode where installed tools' derived states
// or failure-code sets differ.
type disagreement struct {
	Row   *row
	Mode  mode
	Cause *cause // nil: not explained
}

// key is what tools are compared on: derived state and failure codes.
func key(o outcome) string {
	f := slices.Clone(o.Failure)
	slices.Sort(f)
	return o.State + " " + strings.Join(slices.Compact(f), ",")
}

func (r *report) disagreements() []disagreement {
	var out []disagreement
	for i := range r.Rows {
		row := &r.Rows[i]
		for _, m := range modes {
			keys := map[string]bool{}
			for _, res := range row.Results {
				if res.Mode == m && !res.Outcome.Skipped {
					keys[key(res.Outcome)] = true
				}
			}
			if len(keys) > 1 {
				out = append(out, disagreement{Row: row, Mode: m, Cause: explain(row, m)})
			}
		}
	}
	return out
}

func (r *report) unexplained() int {
	n := 0
	for _, d := range r.disagreements() {
		if d.Cause == nil {
			n++
		}
	}
	return n
}

func (r *report) markdown() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	ds := r.disagreements()

	w("# Interoperability report\n\n")
	w("Generated by `go run ./interop` on %s. Do not edit by hand: rerun the command.\n\n", r.Generated.Format("2006-01-02 15:04 MST"))
	w("Every JPEG and PNG fixture in `testdata/`, plus each unsigned fixture signed by C2paSeal ")
	w("(`c2paseal/…`, and `c2paseal+tsa/…` with an RFC 3161 time-stamp from a local test TSA), ")
	w("is validated by each tool in two trust modes:\n\n")
	w("- **default**: the tool's own default trust (C2paSeal and c2patool: no anchors; c2pa-mcp: its embedded C2PA trust list).\n")
	w("- **trusted**: the TEST ONLY root `testdata/pki/trust-anchors.pem` as signing and time-stamping anchor.\n\n")
	w("All signing uses the TEST ONLY PKI in `testdata/pki`, whose private keys are public.\n\n")

	w("## Setup\n\n")
	w("The external validators are separate programs, run as CLIs; nothing is added to `go.mod`. ")
	w("A tool that is not on PATH shows `-` and is never replaced by something else.\n\n")
	w("1. **Verify c2pa-mcp installs first.** Install it and check that it runs before generating the report:\n\n")
	w("   ```\n   go install github.com/richardwooding/c2pa-mcp@v0.7.1\n   c2pa-mcp verify --help\n   ```\n\n")
	w("   If the install or the check fails, stop and fix it; do not substitute the `github.com/richardwooding/c2pa` library.\n")
	w("2. **Add c2patool as the second validator.** It is the Content Authenticity Initiative's official command-line tool (built on c2pa-rs), ")
	w("effectively the reference validator, and this project's oracle. Install a release from <https://github.com/contentauth/c2pa-rs/releases> ")
	w("(or `cargo install c2patool`), then check `c2patool --version`.\n")
	w("3. Run `go run ./interop`.\n\n")
	w("## Tools\n\n| Tool | Version | Status | Notes |\n|---|---|---|---|\n")
	for _, t := range r.Tools {
		status := "run"
		if !t.Installed {
			status = "**not installed** (not on PATH); column shows `-`"
		}
		w("| %s | %s | %s | %s |\n", t.Name, orDash(t.Version), status, t.Note)
	}
	w("| c2pa-rs library wrapper | - | not run | No wrapper is built; c2patool is the c2pa-rs reference CLI and stands in for it. |\n\n")

	w("## How results are compared\n\n")
	w("Tools disagree on their native verdicts by design (c2pa-mcp reports `valid=false` for an untrusted signer, where c2patool reports `Valid`). ")
	w("So each tool's failure codes for the active manifest are reduced to one state with c2pa-rs's rule: ")
	w("any failure other than `signingCredential.untrusted` → **Invalid**; no failures and `signingCredential.trusted` → **Trusted**; otherwise **Valid**; ")
	w("no statuses at all (the tool exited with an error) → **error**. ")
	w("Two tools agree on a file when both the derived state and the set of failure codes match. Success and informational codes are listed per file but not compared.\n\n")

	agree := 0
	for _, row := range r.Rows {
		for _, m := range modes {
			if !slices.ContainsFunc(ds, func(d disagreement) bool { return d.Row.Item.Name == row.Item.Name && d.Mode == m }) {
				agree++
			}
		}
	}
	w("**Summary:** %d files × %d modes = %d checks; tools agree on %d, disagree on %d (%d explained below, %d unexplained).\n\n",
		len(r.Rows), len(modes), len(r.Rows)*len(modes), agree, len(ds), len(ds)-r.unexplained(), r.unexplained())

	w("## Matrix\n\nEach cell: derived state, then failure codes. ✗ marks a file and mode where tools disagree.\n\n")
	w("| File |")
	for _, m := range modes {
		for _, t := range r.Tools {
			w(" %s (%s) |", t.Name, m)
		}
	}
	w("\n|---|")
	for range modes {
		for range r.Tools {
			w("---|")
		}
	}
	w("\n")
	for _, row := range r.Rows {
		mark := ""
		if slices.ContainsFunc(ds, func(d disagreement) bool { return d.Row.Item.Name == row.Item.Name }) {
			mark = " ✗"
		}
		w("| `%s`%s |", row.Item.Name, mark)
		for _, m := range modes {
			for _, t := range r.Tools {
				w(" %s |", cell(row.find(t.Name, m)))
			}
		}
		w("\n")
	}

	w("\n## Disagreements\n\n")
	if len(ds) == 0 {
		w("None: every installed tool gave the same state and failure codes for every file in both modes.\n")
	}
	for _, d := range ds {
		w("### `%s` (%s mode)\n\n", d.Row.Item.Name, d.Mode)
		w("| Tool | State | Native verdict | Failure | Informational |\n|---|---|---|---|---|\n")
		for _, res := range d.Row.Results {
			if res.Mode != d.Mode || res.Outcome.Skipped {
				continue
			}
			o := res.Outcome
			native := o.Native
			if o.Err != "" {
				native = "error: " + o.Err
			}
			w("| %s | %s | %s | %s | %s |\n", res.Tool, o.State, esc(orDash(native)), codes(o.Failure), codes(o.Info))
		}
		w("\n**Container facts** (computed from the file's bytes):\n\n")
		for _, f := range d.Row.Facts {
			w("- %s\n", f)
		}
		w("\n")
		if d.Cause == nil {
			w("**Cause: not explained yet.** Add an entry to `interop/causes.go` after investigating.\n\n")
			continue
		}
		w("**Cause (%s).** %s\n\n", d.Cause.Who, d.Cause.Text)
	}
	return b.String()
}

func (r *row) find(tool string, m mode) outcome {
	for _, res := range r.Results {
		if res.Tool == tool && res.Mode == m {
			return res.Outcome
		}
	}
	return outcome{Skipped: true, State: "-"}
}

func cell(o outcome) string {
	if o.Skipped {
		return "-"
	}
	if o.Err != "" {
		return "error"
	}
	if len(o.Failure) == 0 {
		return o.State
	}
	return o.State + "<br>" + strings.Join(compact(o.Failure), "<br>")
}

func codes(c []string) string {
	if len(c) == 0 {
		return "-"
	}
	return "`" + strings.Join(compact(c), "`, `") + "`"
}

func compact(c []string) []string {
	var out []string
	for _, s := range c {
		if !slices.Contains(out, s) {
			out = append(out, s)
		}
	}
	return out
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func esc(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// containerFacts describes where the manifest store sits in the file and
// checks the hard binding directly from the bytes, independently of any
// validator's report.
func containerFacts(b []byte) []string {
	var facts []string
	add := func(format string, a ...any) { facts = append(facts, fmt.Sprintf(format, a...)) }
	format := asset.Detect(b)
	add("size %d bytes, format %s", len(b), orDash(format))

	var storeStart, storeEnd int
	switch format {
	case asset.JPEG:
		segs, err := jpeg.Segments(b)
		if err != nil {
			add("JPEG segment walk fails: %v", err)
			return facts
		}
		st, err := jpeg.Extract(b)
		if err != nil {
			add("%d JPEG segments; manifest store: %v", len(segs), err)
			return facts
		}
		first, last := st.Segments[0], st.Segments[len(st.Segments)-1]
		storeStart, storeEnd = first.Offset, last.End()
		add("manifest store: %d bytes in %d APP11 segment(s) at file bytes [%d, %d)", len(st.JUMBF), len(st.Segments), storeStart, storeEnd)
	case asset.PNG:
		st, err := png.Extract(b)
		if err != nil {
			add("PNG manifest store: %v", err)
			return facts
		}
		storeStart, storeEnd = st.Chunk.Offset, st.Chunk.End()
		add("manifest store: %d bytes in a caBX chunk at file bytes [%d, %d), CRC valid: %v", len(st.JUMBF), storeStart, storeEnd, st.Chunk.CRCValid)
	default:
		return facts
	}

	_, root, err := asset.Extract(b)
	if err != nil {
		add("store does not parse: %v", err)
		return facts
	}
	ms, err := manifest.DecodeStore(root)
	if err != nil || len(ms) == 0 {
		add("manifests do not decode: %v", err)
		return facts
	}
	active := ms[len(ms)-1]
	add("%d manifest(s); active %s", len(ms), active.Label)
	for _, a := range active.Assertions {
		dh, ok := a.Value.(*assertion.DataHash)
		if !ok {
			continue
		}
		var ex []string
		h := sha256.New()
		pos := 0
		inRange := true
		for _, e := range dh.Exclusions {
			ex = append(ex, fmt.Sprintf("[%d, %d)", e.Start, e.Start+e.Length))
			s, l := int(e.Start), int(e.Length)
			if s < pos || s+l > len(b) || l < 0 {
				inRange = false
				break
			}
			h.Write(b[pos:s])
			pos = s + l
		}
		cover := len(dh.Exclusions) == 1 && int(dh.Exclusions[0].Start) == storeStart && int(dh.Exclusions[0].Start+dh.Exclusions[0].Length) == storeEnd
		add("%s exclusions %s; exactly the store's bytes: %v", a.Label, strings.Join(ex, " "), cover)
		if inRange {
			h.Write(b[pos:])
			add("SHA-256 of the file outside the exclusions matches the recorded hash: %v", fmt.Sprint(string(h.Sum(nil)) == string(dh.Hash)))
		} else {
			add("exclusions are out of order or out of range")
		}
	}
	for _, chk := range active.HashChecks {
		if !chk.Match {
			add("hashed URI %s: the assertion's SHA-256 does not match the hash recorded in the claim", chk.Ref.URL)
		}
	}
	for _, a := range active.Assertions {
		if acts, ok := a.Value.(*assertion.Actions); ok && len(acts.Actions) > 0 {
			add("%s: first action %q", a.Label, acts.Actions[0].Action)
		}
	}
	if s := active.Signature; s != nil {
		add("COSE_Sign1: alg %s, %d-byte signature, %d time-stamp token(s)", orDash(algName(s.Alg)), len(s.Signature), len(s.Timestamps))
		if len(s.X5Chain) > 0 {
			if c, err := x509.ParseCertificate(s.X5Chain[0]); err == nil {
				add("signer certificate %q, valid %s to %s", c.Subject.CommonName, c.NotBefore.UTC().Format(time.RFC3339), c.NotAfter.UTC().Format(time.RFC3339))
			}
		}
		for _, t := range s.Timestamps {
			ts, err := timestamp.Parse(t.Token)
			if err != nil {
				add("time-stamp token does not parse: %v", err)
				continue
			}
			for _, c := range ts.Certificates {
				if !c.IsCA {
					add("time-stamp (sigTst%s): genTime %s, TSA %q issued by %q", map[int]string{1: "", 2: "2"}[t.Version], ts.Time.UTC().Format(time.RFC3339), c.Subject.CommonName, c.Issuer.CommonName)
					break
				}
			}
		}
	} else if active.SignatureErr != nil {
		add("COSE_Sign1 does not decode: %v", active.SignatureErr)
	}
	return facts
}
